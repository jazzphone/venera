#!/usr/bin/env python3
"""gen_static: src/vv_static.h, the fixed binary plists venera-videod answers with, taken from Apple's own host
replies (data/apple-*.bin, captured with tools/pvhost.m): the decoder list cut to the codecs the host GPU decodes,
the supported-properties dictionary, the host info and a plain true."""
import os, plistlib, struct
here = os.path.dirname(os.path.abspath(__file__)) + '/..'

def field(path, key):
    b = open(f'{here}/{path}', 'rb').read()
    tag = f'para,{key}=pls'.encode()
    i = b.index(tag)
    n = struct.unpack('>I', b[i - 4:i])[0]
    return plistlib.loads(b[i + len(tag):i - 4 + n])

# the codecs the host's VA-API driver decodes (Debian's intel-media-va-driver 25.2 on the Iris Xe has no AV1: listing it
# made Safari report AV1 as hardware-decoded and pick it)
decs = [d for d in field('data/apple-decs-reply.bin', 'dec') if set(d['VTCodecType']) & {'avc1', 'hvc1', 'vp09'}]
sup = field('data/apple-dsup-reply.bin', 'sup')
items = {
    'vv_decs_plist': decs,
    'vv_sup_plist': sup,
    'vv_hin_plist': {'VTHostBuildVersion': 'Venera'},
    'vv_true_plist': True,
    # SuggestedQualityOfServiceTiers, as Apple's host answers it (the player degrades through these under load)
    'vv_qos_plist': [{'OnlyTheseFrames': 'AllFrames'}, {'OnlyTheseFrames': 'NonDroppableFrames'},
                     {'OnlyTheseFrames': 'IFrames'}, {'OnlyTheseFrames': 'KeyFrames'}],
}
out = ['// Generated by tools/gen_static.py from Apple host replies (data/); do not edit.', '#include <stdint.h>']
for name, v in items.items():
    b = plistlib.dumps(v, fmt=plistlib.FMT_BINARY)
    out.append(f'static const uint8_t {name}[{len(b)}] = {{')
    for i in range(0, len(b), 20):
        out.append('    ' + ', '.join(f'0x{x:02x}' for x in b[i:i + 20]) + ',')
    out.append('};')
open(f'{here}/src/vv_static.h', 'w').write('\n'.join(out) + '\n')
print('decoders:', [d['VTCodecType'] for d in decs], '; properties:', len(sup))
